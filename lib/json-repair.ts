// Починка одной строки построчного JSON перед разбором.
//
// Живые прогоны на Opus показали: модель иногда не дописывает закрывающую
// фигурную скобку — строка правильна во всём остальном (ключи, кавычки,
// экранирование, кириллица), не хватает ровно одного символа `}`.
// Промпт при этом верный, образец в lib/prompt.ts обе скобки показывает.
//
// Это не разбор текста регулярками: баланс считается посимвольно, а результат
// после починки по-прежнему проходит JSON.parse и доменную схему. Починка —
// попытка, а не обязательство: не получилось — строка отбрасывается, как и раньше.

// Недостача больше трёх скобок означает, что пришло что-то совсем другое,
// а не потерянный хвост объекта. Такое чинить не надо.
const MAX_MISSING_BRACES = 3;

/**
 * Дописывает недостающие закрывающие фигурные скобки. Скобки внутри строковых
 * литералов (в тексте концепции вполне может встретиться `{` или `}`) на счёт
 * не влияют, экранированные кавычки учитываются.
 *
 * Возвращает null, если чинить нечего или незачем: баланс сошёлся, закрывающих
 * скобок наоборот больше, чем открывающих, или недостача слишком велика.
 * Ничего кроме закрывающих фигурных скобок не добавляется и не удаляется.
 */
export function closeJsonBraces(line: string): string | null {
  let depth = 0;
  let inString = false;
  let escaped = false;

  for (const char of line) {
    if (escaped) {
      escaped = false;
      continue;
    }
    if (inString) {
      if (char === "\\") escaped = true;
      else if (char === '"') inString = false;
      continue;
    }
    if (char === '"') inString = true;
    else if (char === "{") depth += 1;
    else if (char === "}") depth -= 1;
  }

  if (depth <= 0 || depth > MAX_MISSING_BRACES) return null;
  return line + "}".repeat(depth);
}
